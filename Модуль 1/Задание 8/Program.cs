using System;

class Program
{
    static void Main()
    {
        //Ввод количества простых чисел K
        Console.Write("Введите количество простых чисел K: ");
        if (!int.TryParse(Console.ReadLine(), out int k) || k <= 0)
        {
            Console.WriteLine("Ошибка: K должно быть целым положительным числом.");
            return;
        }

        Console.WriteLine($"\nПервые {k} простых чисел:");

        int count = 0;       // Счетчик найденных простых чисел
        int number = 2;      // Число, которое мы проверяем (первое простое число — это 2)

        //Главный цикл, пока не найдем ровно K простых чисел
        while (count < k)
        {
            if (IsPrime(number))
            {
                count++;

                //Выводим число и добавляем знак табуляции для ровных колонок
                Console.Write(number + "\t");

                // Если нашли очередные 10 чисел, переносим строку
                if (count % 10 == 0)
                {
                    Console.WriteLine();
                }
            }
            number++; // Переходим к следующему числу для проверки
        }

        Console.WriteLine(); // Финальный отступ в конце программы
    }

    // 3. Метод (функция) для проверки, является ли число простым
    static bool IsPrime(int n)
    {
        if (n < 2) return false;

        // Оптимальный алгоритм: проверяем делители до квадратного корня из числа
        for (int i = 2; i * i <= n; i++)
        {
            if (n % i == 0)
            {
                return false; //Если число на что-то разделилось без остатка — оно не простое
            }
        }
        return true; //Если делителей не нашли — число простое
    }
}

